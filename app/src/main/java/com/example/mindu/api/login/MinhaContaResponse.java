package com.example.mindu.api.login;

public class MinhaContaResponse {

    private String id;
    private String nome;
    private String email;
    private String tipo;
    private String status;

    public String getId() {
        return id;
    }

    public String getNome() {
        return nome;
    }

    public String getEmail() {
        return email;
    }

    public String getTipo() {
        return tipo;
    }

    public String getStatus() {
        return status;
    }
}